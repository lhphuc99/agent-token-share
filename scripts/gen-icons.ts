// Copies the codicons the panel uses into media/icons.js, so the webview needs no icon font.
import { readFileSync, writeFileSync } from "node:fs";

const NAMES = [
  "add", "arrow-left", "check", "close", "copy", "edit", "ellipsis", "error", "eye", "eye-closed",
  "folder-opened", "inbox", "info", "key", "refresh", "save", "search", "sparkle", "trash", "warning",
];
const DIR = "node_modules/@vscode/codicons/src/icons";

const icons: Record<string, string> = {};
for (const name of NAMES) {
  const svg = readFileSync(`${DIR}/${name}.svg`, "utf8");
  icons[name] = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
}
writeFileSync(
  "media/icons.js",
  `// Generated by scripts/gen-icons.ts from @vscode/codicons (CC BY 4.0, Microsoft). Do not edit.\nwindow.CODICONS = ${JSON.stringify(icons)};\n`,
);
console.log(`wrote ${NAMES.length} icons to media/icons.js`);
